/**
 * Carga direta de um arquivo na tabela final, sem regras de qualidade.
 *
 * 1. O próprio PostgreSQL lê o CSV (COPY nativo) para uma tabela de carga
 *    UNLOGGED, com uma coluna de texto por coluna do arquivo. Sem índice e sem
 *    WAL, é a escrita mais barata que o banco oferece — e, ao contrário de uma
 *    tabela temporária, as outras conexões a enxergam.
 * 2. O arquivo é gravado em fact_preco_coletado por várias conexões ao mesmo
 *    tempo, cada uma com uma parte das chaves (hash do GTIN): um INSERT não
 *    usa mais de um núcleo do banco, e as partes somam os demais. A mesma
 *    chave cai sempre na mesma parte, então as partes nunca se esperam.
 *
 * Nada é validado além do que a tabela final exige para aceitar a linha:
 * chave (gtin, loja, data) preenchida, data legível e preço que caiba em
 * numeric(12,2). A linha que não tem isso não tem como ser gravada e é só
 * contada — não vai para ctl_rejeicao.
 *
 * Cada parte é uma transação. Se uma falhar, as outras podem já ter gravado:
 * o arquivo fica com erro e reprocessá-lo completa o que faltou — o UPSERT só
 * reescreve o que mudou.
 *
 * Se o COPY nativo recusar o arquivo (aspas fora do padrão, byte inválido), o
 * arquivo é relido pelo leitor tolerante em Node, mais lento, e segue igual.
 */

/** Prefixo das tabelas de carga; as que sobram de um processo morto são apagadas na subida. */
export const PREFIXO_TABELA_CARGA = 'tmp_carga_';

/** O maior valor que cabe em numeric(12,2), com o arredondamento da coluna. */
const LIMITE_PRECO = '9999999999.995';

/** O UPSERT recusa o comando que atualizaria a mesma chave duas vezes. */
const ERRO_LINHA_REPETIDA = '21000';

export interface ParametrosCargaRapida {
  idExecucao: number;
  idArquivo: number;
  caminhoLocal: string;
  fonte: string;
  /** Em quantas conexões o arquivo é gravado ao mesmo tempo. */
  partes: number;
  /** Lança se a parada da coleta foi pedida. */
  verificar: () => Promise<void>;
  /** Registra o backend para que uma parada interrompa a consulta em curso. */
  comPid: <T>(pid: number, fn: () => Promise<T>) => Promise<T>;
  /** Uma transação do arquivo abriu / fechou no backend `pid`. */
  aoAbrir: (cliente: Cliente, pid: number, rotulo: string) => Promise<void>;
  aoFechar: (pid: number) => void;
  /** Linhas lidas até agora (aproximado no COPY nativo: conta quebras de linha). */
  aoProgresso: (linhas: number) => Promise<void>;
  /** Avisado a cada passo, para o acompanhamento da gravação. */
  aoPasso: (passo: 'partições' | 'gravação', detalhe?: string) => Promise<void>;
  /** O COPY nativo recusou o arquivo e ele vai ser relido em modo tolerante. */
  aoReler: (motivo: string) => Promise<void>;
}

export interface ResultadoCargaRapida {
  linhas: number;
  inseridas: number;
  atualizadas: number;
  /** Lidas e não gravadas: sem chave ou preço, repetidas ou iguais às já gravadas. */
  naoGravadas: number;
  modo: 'nativo' | 'tolerante';
  /** Só no modo tolerante. */
  recuperadas: number;
  malformadas: number;
  cabecalho: string[];
  particoes: string[];
}

export async function carregarArquivoRapido(
  p: ParametrosCargaRapida,
): Promise<ResultadoCargaRapida> {
  const info = await lerCabecalho(p.caminhoLocal);
  const colunas = Array.from({ length: info.colunas.length }, (_, i) => `c${i + 1}`);
  const tabela = `infoprice.${PREFIXO_TABELA_CARGA}${p.idExecucao}_${p.idArquivo}`;
  const x = expressoes(info);
  const partes = Math.max(1, Math.trunc(p.partes));

  try {
    // ── 1 · arquivo → tabela de carga ─────────────────────────────────────
    const lido = await emTransacao(
      (cliente) =>
        comBackend(p, cliente, 'leitura', async () => {
          await cliente.query(`DROP TABLE IF EXISTS ${tabela}`);
          await cliente.query(
            `CREATE UNLOGGED TABLE ${tabela} (
               _n bigint GENERATED BY DEFAULT AS IDENTITY,
               ${colunas.map((c) => `${c} text`).join(', ')}
             )`,
          );

          let modo: 'nativo' | 'tolerante' = 'nativo';
          let linhas: number;
          let recuperadas = 0;
          let malformadas = 0;
          await cliente.query('SAVEPOINT copia_nativa');
          try {
            linhas = await copiaNativa(p, cliente, tabela, info, colunas);
            await cliente.query('RELEASE SAVEPOINT copia_nativa');
          } catch (erro) {
            if (erro instanceof ExecucaoCancelada) throw erro;
            await cliente.query('ROLLBACK TO SAVEPOINT copia_nativa');
            await p.aoReler(erro instanceof Error ? erro.message : String(erro));
            modo = 'tolerante';
            const r = await copiaTolerante(p, cliente, tabela, colunas);
            linhas = r.linhas;
            recuperadas = r.recuperadas;
            malformadas = r.malformadas;
          }

          await p.aoPasso('partições');
          const { rows: meses } = await cliente.query<{ mes: string }>(
            `SELECT DISTINCT date_trunc('month', ${x.data})::date::text AS mes
               FROM ${tabela} r
              WHERE ${x.data} IS NOT NULL`,
          );
          return { linhas, modo, recuperadas, malformadas, meses: meses.map((m) => m.mes) };
        }),
      { longa: true },
    );

    // ── 2 · partições mensais, cada uma na sua transação curta ────────────
    // Criar partição trava a tabela final até o fim da transação que a cria;
    // aqui ela dura só o CREATE, e as partes ainda não começaram.
    const particoes: string[] = [];
    for (const mes of lido.meses) {
      const { rows } = await pool.query<{ nome: string }>(
        'SELECT infoprice.garantir_particao($1::date) AS nome',
        [mes],
      );
      if (rows[0]) particoes.push(rows[0].nome);
    }

    // ── 3 · gravação no fato, em partes paralelas ─────────────────────────
    await p.verificar();
    await p.aoPasso(
      'gravação',
      `${partes} parte(s) em paralelo · ${particoes.length} partição(ões)`,
    );
    const fim = await Promise.allSettled(
      Array.from({ length: partes }, (_, parte) =>
        emTransacao(
          (cliente) =>
            comBackend(p, cliente, `parte ${parte + 1}/${partes}`, () =>
              gravarParte(cliente, tabela, x, p, parte, partes),
            ),
          { longa: true },
        ),
      ),
    );
    const falha = fim.find((r): r is PromiseRejectedResult => r.status === 'rejected');
    if (falha) throw falha.reason;
    const gravadas = fim
      .map((r) => (r as PromiseFulfilledResult<{ inseridas: number; atualizadas: number }>).value)
      .reduce(
        (t, g) => ({ inseridas: t.inseridas + g.inseridas, atualizadas: t.atualizadas + g.atualizadas }),
        { inseridas: 0, atualizadas: 0 },
      );

    return {
      linhas: lido.linhas,
      inseridas: gravadas.inseridas,
      atualizadas: gravadas.atualizadas,
      naoGravadas: lido.linhas - gravadas.inseridas - gravadas.atualizadas,
      modo: lido.modo,
      recuperadas: lido.recuperadas,
      malformadas: lido.malformadas,
      cabecalho: info.colunas,
      particoes,
    };
  } finally {
    await pool.query(`DROP TABLE IF EXISTS ${tabela}`).catch(() => undefined);
  }
}

/**
 * Apaga as tabelas de carga que sobraram de um processo que morreu no meio de
 * um arquivo. Só as de execuções que não estão mais em andamento: uma coleta
 * rodando em outro processo (o ingest no terminal) segue com a sua.
 */
export async function apagarTabelasDeCargaOrfas(): Promise<number> {
  const { rows } = await pool.query<{ nome: string }>(
    `SELECT c.relname AS nome
       FROM pg_class c
       JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = 'infoprice'
        AND c.relkind = 'r'
        AND c.relname LIKE $1
        AND NOT EXISTS (
          SELECT 1 FROM infoprice.ctl_execucao e
           WHERE e.status = 'em_execucao'
             AND c.relname LIKE $2 || e.id || '\_%'
        )`,
    [`${PREFIXO_TABELA_CARGA.replace(/_/g, '\_')}%`, PREFIXO_TABELA_CARGA.replace(/_/g, '\_')],
  );
  for (const { nome } of rows) {
    await pool.query(`DROP TABLE IF EXISTS infoprice.${nome.replace(/[^a-z0-9_]/g, '')}`);
  }
  return rows.length;
}

/** Roda `fn` com o backend da conexão registrado na parada e no acompanhamento. */
async function comBackend<T>(
  p: ParametrosCargaRapida,
  cliente: Cliente,
  rotulo: string,
  fn: () => Promise<T>,
): Promise<T> {
  const { rows } = await cliente.query<{ pid: number }>('SELECT pg_backend_pid() AS pid');
  const pid = rows[0]!.pid;
  return p.comPid(pid, async () => {
    await p.aoAbrir(cliente, pid, rotulo);
    try {
      return await fn();
    } finally {
      p.aoFechar(pid);
    }
  });
}

/**
 * Uma parte do arquivo no fato. Primeiro sem deduplicar, que é o caso comum e
 * o mais rápido. Se a parte trouxer a mesma chave duas vezes, o PostgreSQL
 * recusa o UPSERT (uma linha não pode ser atualizada duas vezes no mesmo
 * comando): aí refaz ficando só com a última ocorrência de cada chave.
 */
async function gravarParte(
  cliente: Cliente,
  tabela: string,
  x: Expressoes,
  p: ParametrosCargaRapida,
  parte: number,
  partes: number,
): Promise<{ inseridas: number; atualizadas: number }> {
  // Ordenação e hash da deduplicação em memória, e COMMIT sem esperar o
  // disco: se o banco cair antes do flush, a parte volta como não gravada e
  // o reprocessamento a refaz.
  await cliente.query(`SET LOCAL work_mem = '${config.coleta.memoriaCarga}'`);
  await cliente.query('SET LOCAL synchronous_commit = off');
  await cliente.query('SAVEPOINT gravacao');
  try {
    return await gravar(cliente, tabela, x, p, parte, partes, false);
  } catch (erro) {
    if ((erro as { code?: string }).code !== ERRO_LINHA_REPETIDA) throw erro;
    await cliente.query('ROLLBACK TO SAVEPOINT gravacao');
    return await gravar(cliente, tabela, x, p, parte, partes, true);
  }
}

/** O arquivo, descompactado, direto no COPY do PostgreSQL. */
async function copiaNativa(
  p: ParametrosCargaRapida,
  cliente: Cliente,
  tabela: string,
  info: InfoCabecalho,
  colunas: string[],
): Promise<number> {
  const delim = info.delimitador.replace(/'/g, "''");
  const destino = cliente.query(
    copyFrom(
      `COPY ${tabela} (${colunas.join(', ')}) FROM STDIN WITH (
         FORMAT csv, HEADER ${info.semCabecalho ? 'false' : 'true'},
         DELIMITER '${delim}', NULL '\\N', QUOTE '"', ESCAPE '\\'
       )`,
    ),
  );

  // Conta as quebras de linha só para o progresso; o total certo vem do COPY.
  let quebras = 0;
  const contador = new Transform({
    transform(pedaco: Buffer, _cod, feito) {
      let i = -1;
      while ((i = pedaco.indexOf(10, i + 1)) !== -1) quebras += 1;
      p.verificar()
        .then(() => p.aoProgresso(quebras))
        .then(() => feito(null, pedaco), feito);
    },
  });

  const entrada = fs.createReadStream(p.caminhoLocal);
  if (p.caminhoLocal.endsWith('.gz')) {
    await pipeline(entrada, zlib.createGunzip(), contador, destino);
  } else {
    await pipeline(entrada, contador, destino);
  }
  return destino.rowCount;
}

/**
 * O leitor tolerante em Node, para o arquivo que o COPY nativo recusou. A
 * linha que nem ele consegue separar em colunas fica de fora e só é contada.
 */
async function copiaTolerante(
  p: ParametrosCargaRapida,
  cliente: Cliente,
  tabela: string,
  colunas: string[],
): Promise<{ linhas: number; recuperadas: number; malformadas: number }> {
  const destino = cliente.query(
    copyFrom(
      `COPY ${tabela} (_n, ${colunas.join(', ')}) FROM STDIN WITH (FORMAT csv)`,
    ),
  );
  // Strings sempre entre aspas: '' chega como texto vazio e null (sem aspas)
  // como NULL — o mesmo que o \N vira no COPY nativo.
  const gerador = stringify({ quoted_string: true });

  let falhaCopy: unknown = null;
  const copia = pipeline(gerador, destino).catch((erro) => {
    falhaCopy = erro;
    throw erro;
  });
  copia.catch(() => undefined);

  const esperarVazao = () =>
    Promise.race([
      new Promise<void>((r) => gerador.once('drain', () => r())),
      copia.then(
        () => undefined,
        () => undefined,
      ),
    ]);

  let enviadas = 0;
  try {
    const resultado = await lerCsv(p.caminhoLocal, async (lote) => {
      await p.verificar();
      for (const linha of lote) {
        if (falhaCopy) throw falhaCopy;
        if (linha.erro) continue;
        const valores = colunas.map((_, i) => {
          const v = linha.valores[i];
          return v === undefined || v === NULO ? null : v;
        });
        if (!gerador.write([linha.numeroLinha, ...valores])) await esperarVazao();
      }
      enviadas += lote.length;
      await p.aoProgresso(enviadas);
    });

    gerador.end();
    await copia;
    return {
      linhas: resultado.linhas,
      recuperadas: resultado.recuperadas,
      malformadas: resultado.malformadas,
    };
  } catch (erro) {
    gerador.destroy();
    await copia.catch(() => undefined);
    throw erro;
  }
}

interface Expressoes {
  gtin: string;
  loja: string;
  data: string;
  preco: string;
  /** Colunas do fato (sem as de controle) e a expressão de cada uma. */
  campos: [string, string][];
}

/**
 * Conversão de texto para número e data escrita direto na consulta.
 *
 * infoprice.para_numero e para_data são plpgsql com bloco EXCEPTION: cada
 * chamada abre uma subtransação, e são dezenas de chamadas por linha. Aqui o
 * formato comum (1234.56, 2026-10-28) converte pela expressão regular, que o
 * PostgreSQL avalia sem chamada de função; só o que foge dele (vírgula
 * decimal, dd/mm/aaaa, dia 29 a 31 que pode não existir) passa pela função.
 */
function numero(v: string): string {
  return `CASE WHEN ${v} ~ '^-?[0-9]+(\\.[0-9]+)?$' THEN (${v})::numeric ` +
    `WHEN ${v} IS NULL THEN NULL ELSE infoprice.para_numero(${v}) END`;
}

function data(v: string): string {
  return `CASE WHEN ${v} ~ '^[0-9]{4}-(0[1-9]|1[0-2])-(0[1-9]|1[0-9]|2[0-8])' ` +
    `THEN substr(${v}, 1, 10)::date ` +
    `WHEN ${v} IS NULL THEN NULL ELSE infoprice.para_data(${v}) END`;
}

/**
 * As expressões SQL que levam as colunas do arquivo (c1…cN) às do fato. Os
 * mesmos nomes, sinônimos e derivações do leitor (ver leitor-csv.ts): entre
 * colunas que caem no mesmo nome interno vale o primeiro valor não vazio, e
 * preço, promoção e tipo de preço saem de preco_regular, preco_pago e
 * flag_promocao.
 */
function expressoes(info: InfoCabecalho): Expressoes {
  const primeiro = (indices: number[]) => {
    const partes = indices.map((i) => `NULLIF(btrim(r.c${i + 1}), '')`);
    if (partes.length === 0) return 'NULL::text';
    return partes.length === 1 ? partes[0]! : `COALESCE(${partes.join(', ')})`;
  };
  const indices = (nomes: string[], alvo: string) =>
    nomes.flatMap((nome, i) => (nome === alvo ? [i] : []));
  /** Campo interno (gtin, id_loja, preco…), com sinônimos. */
  const campo = (nome: string) => primeiro(indices(info.colunas, nome));
  /** Coluna do arquivo pelo nome original. */
  const original = (nome: string) => primeiro(indices(info.nomesOriginais, nome));

  const promocao = `COALESCE(${campo('flag_promocao')} ~* '^(true|1|s|sim|y|yes)$', false)`;
  const precoPromocional = numero(
    `COALESCE(${campo('preco_promocional')}, CASE WHEN ${promocao} THEN ${campo('preco_pago')} END)`,
  );

  const gtin = campo('gtin');
  const loja = campo('id_loja');
  const dataColeta = data(campo('data_coleta'));
  const preco = numero(`COALESCE(${campo('preco')}, ${campo('preco_pago')})`);

  const campos: [string, string][] = [
    ['gtin', gtin],
    ['id_loja', loja],
    ['data_coleta', dataColeta],
    ['descricao', campo('descricao')],
    ['rede', campo('rede')],
    ['uf', campo('uf')],
    ['municipio', campo('municipio')],
    ['preco', preco],
    // Um promocional que não cabe na coluna fica vazio em vez de derrubar o arquivo.
    ['preco_promocional', `CASE WHEN abs(${precoPromocional}) < ${LIMITE_PRECO} THEN ${precoPromocional} END`],
    [
      'tipo_preco',
      `COALESCE(${campo('tipo_preco')}, CASE WHEN ${campo('flag_promocao')} IS NOT NULL ` +
        `THEN CASE WHEN ${promocao} THEN 'Promoção' ELSE 'Regular' END END, 'Regular')`,
    ],
    ...COLUNAS_ORIGEM.map((c): [string, string] => {
      const v = original(c.origem);
      if (c.tipo === 'numero') return [c.nome, numero(v)];
      if (c.tipo === 'booleano') return [c.nome, `infoprice.para_booleano(${v})`];
      return [c.nome, v];
    }),
  ];

  return { gtin, loja, data: dataColeta, preco, campos };
}

/** O UPSERT de uma parte do arquivo em fact_preco_coletado. */
async function gravar(
  cliente: Cliente,
  tabela: string,
  x: Expressoes,
  p: ParametrosCargaRapida,
  parte: number,
  partes: number,
  deduplicar: boolean,
): Promise<{ inseridas: number; atualizadas: number }> {
  // A parte: as chaves cujo hash do GTIN cai nela. Com uma parte só, todas.
  const naParte =
    partes > 1 ? `(hashtext(${x.gtin}) & 2147483647) % ${partes} = ${parte} AND ` : '';
  // O mínimo para a linha caber no fato: chave preenchida e preço válido.
  const gravavel =
    `${naParte}${x.gtin} IS NOT NULL AND ${x.loja} IS NOT NULL AND ${x.data} IS NOT NULL ` +
    `AND ${x.preco} IS NOT NULL AND abs(${x.preco}) < ${LIMITE_PRECO}`;
  const ultimas = deduplicar
    ? `AND r._n IN (
         SELECT max(r._n) FROM ${tabela} r
          WHERE ${gravavel}
          GROUP BY ${x.gtin}, ${x.loja}, ${x.data}
       )`
    : '';

  const nomes = x.campos.map(([nome]) => nome);
  // Chave e controle ficam de fora do SET; descrição, rede, UF e cidade não
  // apagam o que já existe quando a linha nova vem sem elas.
  const preservados = new Set(['descricao', 'rede', 'uf', 'municipio']);
  const atualizaveis = nomes.filter((c) => !['gtin', 'id_loja', 'data_coleta'].includes(c));
  const novo = (c: string) => (preservados.has(c) ? `COALESCE(EXCLUDED.${c}, f.${c})` : `EXCLUDED.${c}`);

  const { rows } = await cliente.query<{ inseridas: number; atualizadas: number }>(
    `WITH gravadas AS (
       INSERT INTO infoprice.fact_preco_coletado AS f (
         ${nomes.join(', ')}, fonte, id_execucao, id_arquivo, numero_linha
       )
       SELECT ${x.campos.map(([, expr]) => expr).join(',\n              ')},
              $1, $2::bigint, $3::bigint, r._n
         FROM ${tabela} r
        WHERE ${gravavel}
        ${ultimas}
       ON CONFLICT (gtin, id_loja, data_coleta, fonte) DO UPDATE
          SET ${atualizaveis.map((c) => `${c} = ${novo(c)}`).join(',\n              ')},
              id_execucao   = EXCLUDED.id_execucao,
              id_arquivo    = EXCLUDED.id_arquivo,
              numero_linha  = EXCLUDED.numero_linha,
              atualizado_em = now()
        -- Só reescreve a linha que mudou de fato: reprocessar o mesmo arquivo
        -- não toca no que já está igual.
        WHERE (${atualizaveis.map((c) => `f.${c}`).join(', ')})
              IS DISTINCT FROM
              (${atualizaveis.map(novo).join(', ')})
       RETURNING (f.criado_em = f.atualizado_em) AS foi_insert
     )
     SELECT count(*) FILTER (WHERE foi_insert)::bigint     AS inseridas,
            count(*) FILTER (WHERE NOT foi_insert)::bigint AS atualizadas
       FROM gravadas`,
    [p.fonte, p.idExecucao, p.idArquivo],
  );
  return rows[0] ?? { inseridas: 0, atualizadas: 0 };
}

/**
 * O comando de persistência exibido na tela de detalhe da execução — o
 * mesmo que gravar() monta.
 */
export const SQL_PERSISTENCIA = `-- 1 · o PostgreSQL lê o arquivo direto, para uma tabela de carga sem WAL
COPY tmp_carga FROM STDIN (FORMAT csv, HEADER, DELIMITER '|', NULL '\\N');

-- 2 · N conexões gravam ao mesmo tempo, cada uma com uma parte das chaves
INSERT INTO infoprice.fact_preco_coletado AS f
SELECT … FROM tmp_carga                 -- todas as colunas, já convertidas
WHERE hashtext(gtin) % N = :parte       -- a parte desta conexão
  AND gtin, loja, data e preço legíveis  -- o mínimo que a tabela exige
ON CONFLICT (gtin, id_loja, data_coleta, fonte)
DO UPDATE SET preco = EXCLUDED.preco, …,  -- e as demais colunas
              id_execucao = EXCLUDED.id_execucao,
              atualizado_em = now()
WHERE (f.preco, …) IS DISTINCT FROM (EXCLUDED.preco, …);  -- só se algo mudou`;
